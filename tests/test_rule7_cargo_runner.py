"""Rule 7 for Rust: the suite is measured by `cargo test`, read from the harness's JSON, and the
exit status must agree. These tests build tiny real crates, so they need cargo and skip without it.
"""
import shutil
from pathlib import Path

import pytest

from warden.authorization import grant
from warden.guard import Snapshot, is_protected, iter_tree
from warden.suite import CargoSuiteRun, detect_runner, run_suite
from warden.tagteam import TagTeam

from fakes import FakeDrafter

needs_cargo = pytest.mark.skipif(shutil.which("cargo") is None, reason="cargo is not installed")


def _crate(root: Path, test_body: str = "assert_eq!(super::VALUE, 1);") -> None:
    (root / "src").mkdir()
    (root / "Cargo.toml").write_text('[package]\nname = "demo"\nversion = "0.1.0"\nedition = "2021"\n',
                                     encoding="utf-8")
    (root / "src" / "lib.rs").write_text(
        f"pub const VALUE: u32 = 1;\n\n#[cfg(test)]\nmod t {{\n    #[test]\n    fn value() {{ {test_body} }}\n}}\n",
        encoding="utf-8")
    (root / "Cargo.lock").write_text('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n'
                                     'version = 3\n\n[[package]]\nname = "demo"\nversion = "0.1.0"\n', encoding="utf-8")


def test_a_rust_project_without_python_tests_picks_cargo(tmp_path: Path):
    _crate(tmp_path)
    assert detect_runner(tmp_path) == "cargo"


def test_python_wins_when_both_are_present(tmp_path: Path):
    _crate(tmp_path)
    (tmp_path / "pyproject.toml").write_text("[project]\nname='x'\n", encoding="utf-8")
    assert detect_runner(tmp_path) == "pytest"


def test_a_test_file_alone_also_means_pytest(tmp_path: Path):
    _crate(tmp_path)
    (tmp_path / "tools").mkdir()
    (tmp_path / "tools" / "test_helper.py").write_text("def test_x():\n    pass\n", encoding="utf-8")
    assert detect_runner(tmp_path) == "pytest"


def test_no_cargo_manifest_means_pytest(tmp_path: Path):
    assert detect_runner(tmp_path) == "pytest"


def test_an_unknown_runner_is_not_run(tmp_path: Path):
    result = run_suite(tmp_path, "python", runner="gradle")
    assert not result.ran and "unknown suite runner" in result.reason


@needs_cargo
def test_a_green_crate_is_green(tmp_path: Path):
    _crate(tmp_path)
    result = run_suite(tmp_path, "python", runner="cargo", timeout=300)
    assert isinstance(result, CargoSuiteRun) and result.green, result.describe()
    assert result.passed == 1 and result.failed == 0
    assert not (tmp_path / "target").exists(), "build output must not land in the target's tree"


@needs_cargo
def test_a_failing_test_is_red_and_says_cargo(tmp_path: Path):
    _crate(tmp_path, "assert_eq!(super::VALUE, 2);")
    result = run_suite(tmp_path, "python", runner="cargo", timeout=300)
    assert result.ran and not result.green and result.failed == 1
    assert "cargo exited" in result.describe() and "pytest" not in result.describe()


@needs_cargo
def test_a_crate_that_does_not_build_did_not_run(tmp_path: Path):
    _crate(tmp_path)
    (tmp_path / "src" / "lib.rs").write_text("pub const VALUE: u32 = ;\n", encoding="utf-8")
    result = run_suite(tmp_path, "python", runner="cargo", timeout=300)
    assert not result.green


@needs_cargo
def test_a_crate_with_no_tests_did_not_run(tmp_path: Path):
    _crate(tmp_path)
    (tmp_path / "src" / "lib.rs").write_text("pub const VALUE: u32 = 1;\n", encoding="utf-8")
    result = run_suite(tmp_path, "python", runner="cargo", timeout=300)
    assert not result.ran and "no tests" in result.reason


@needs_cargo
def test_forged_results_written_straight_to_stdout_cannot_make_a_failing_run_green(tmp_path: Path):
    forged = r'{"type":"suite","event":"ok","passed":9,"failed":0,"ignored":0}'
    body = ('use std::io::Write; let mut out = std::io::stdout(); '
            f'out.write_all(b"\\n{forged.replace(chr(34), chr(92) + chr(34))}\\n").unwrap(); out.flush().unwrap(); '
            'assert_eq!(super::VALUE, 2);')
    _crate(tmp_path, body)
    result = run_suite(tmp_path, "python", runner="cargo", timeout=300)
    assert result.ran and not result.green and result.failed == 1, result.describe()


@needs_cargo
def test_the_gate_puts_back_a_change_that_breaks_a_rust_suite(tmp_path: Path):
    _crate(tmp_path)
    (tmp_path / "NOTE.md").write_text("old note\n", encoding="utf-8")
    drafter = FakeDrafter(steps=("pub const VALUE: u32 = 2;\n\n#[cfg(test)]\nmod t {\n    #[test]\n"
                                 "    fn value() { assert_eq!(super::VALUE, 1); }\n}\n",), path="src/lib.rs")
    auth = grant("william", "transform", str(tmp_path.resolve()), "code", "rust rule 7 test")
    result = TagTeam(drafter=drafter, suite_timeout=300).run(tmp_path, findings=[], authorization=auth)
    assert result.decision == "REJECT" and not result.applied
    assert "VALUE: u32 = 1" in (tmp_path / "src" / "lib.rs").read_text(encoding="utf-8")
    assert result.suite_before.green and result.suite_after.failed == 1
    assert any("(cargo)" in n for n in result.notes)


def test_rust_build_and_test_files_are_protected():
    for rel in ("Cargo.toml", "crates/a/Cargo.toml", "build.rs", "crates/a/build.rs", "rust-toolchain.toml",
                ".cargo/config.toml", "crates/a/tests/redteam.rs", "src/tests.rs", "src/gate_test.rs"):
        assert is_protected(rel), rel
    assert not is_protected("crates/a/src/lib.rs")


def test_cargo_build_output_is_not_walked_but_an_ordinary_target_folder_is(tmp_path: Path):
    (tmp_path / "Cargo.toml").write_text("[package]\nname='x'\n", encoding="utf-8")
    (tmp_path / "target" / "debug").mkdir(parents=True)
    (tmp_path / "target" / "debug" / "big.bin").write_bytes(b"x" * 10)
    (tmp_path / "docs" / "target").mkdir(parents=True)
    (tmp_path / "docs" / "target" / "keep.md").write_text("kept\n", encoding="utf-8")
    walked = {p.relative_to(tmp_path).as_posix() for p in iter_tree(tmp_path)}
    assert "target/debug/big.bin" not in walked and "target/debug" not in walked
    assert "docs/target/keep.md" in walked
    assert "target/debug/big.bin" not in Snapshot(tmp_path).files
