"""The seams: what Warden checks about its own seat-fillers instead of trusting them.

Drafter "never writes", Ghost "reports only", Burnish "writes only through
Warden". Those are charters. Until now they were enforced by tests that read
each repo's imports, which proves nothing about what the code does when it
runs. Warden loads these seats by name into its own process, so it checks the
one thing it can see: did the tree change while a seat had control?

Also here: what an edit may touch (inside the target, inside the grant's
scope, outside the files that judge the work).
"""

from __future__ import annotations

import ast
import fnmatch
import unicodedata
from contextlib import contextmanager
from pathlib import Path, PurePosixPath
from typing import Dict, Iterable, Iterator, Optional

from . import gitstate, textio
from .authorization import Authorization
from .models import Transformation

_SKIP = {".git", "__pycache__", ".pytest_cache", ".venv", "node_modules", ".mypy_cache", ".ruff_cache"}
#: Folders the snapshot does not read (an installed environment can be huge) but does watch by name,
#: size and time: a seat that drops a library, a `.pth` file or a hook in here would run later with the
#: user's rights. Pure caches (`__pycache__`, `.ruff_cache`, ...) are not watched; the suite never reads
#: `__pycache__` from the tree (see `suite.py`), so a planted .pyc cannot change its result.
_ENV_DIRS = {".venv", "venv", "env", "node_modules"}
#: Past this many bytes in total the tree is fingerprinted but not restorable.
_RESTORE_LIMIT = 200 * 1024 * 1024

#: Prose a documentation grant may touch.
PROSE = {".md", ".rst", ".txt"}

#: The files that decide whether a change is acceptable, or how the code is built, tested and
#: shipped. A proposer that can edit them is grading its own work or changing what runs later.
#: Names are compared case-insensitively (after NFKC) and as glob patterns.
_PROTECTED_NAMES = {
    # test and build configuration
    "conftest.py", "pytest.ini", ".pytest.ini", "tox.ini", "setup.cfg", "setup.py", "pyproject.toml",
    "noxfile.py", ".coveragerc", "makefile", "gnumakefile", "justfile", "tests.py", ".pre-commit-config.yaml",
    # CI
    ".gitlab-ci.yml", ".gitlab-ci.yaml", "jenkinsfile", "azure-pipelines.yml", "azure-pipelines.yaml",
    ".travis.yml", "appveyor.yml", "bitbucket-pipelines.yml", "cloudbuild.yaml", "cloudbuild.yml",
    ".drone.yml", "codecov.yml", ".codecov.yml",
    # dependencies and submodules
    ".gitmodules", "pipfile", "pipfile.lock", "poetry.lock", "uv.lock", "pdm.lock", "package-lock.json",
    "yarn.lock", "pnpm-lock.yaml", "cargo.lock", "gemfile.lock", "composer.lock", "go.sum",
    # containers
    "dockerfile",
}
_PROTECTED_PATTERNS = (
    "pytest*.ini", ".pytest*.ini", "test_*", "*_test.py", "*.lock",
    "requirements*.txt", "constraints*.txt", "requirements*.in", "constraints*.in",
    "*requirements*.txt", "*constraints*.txt",
    "dockerfile*", "*.dockerfile", "docker-compose*.yml", "docker-compose*.yaml", "compose*.yml", "compose*.yaml",
    "jenkinsfile*", "azure-pipelines*.yml", "*.gitlab-ci.yml", ".ghost_*",
)
_PROTECTED_DIRS = {"tests", "test", "testing", ".github", ".circleci", ".githooks", ".gitlab", ".buildkite",
                   ".husky", ".azure-pipelines"}
#: Any file or folder whose name starts with this is Ghost's own bookkeeping (ledger, baseline, archive marker).
_PROTECTED_DIR_PATTERNS = (".ghost_*",)

#: Version control, environments and caches. Nothing in them is the project's
#: source, and a hook or a library edited there runs later with the user's rights.
FORBIDDEN_DIRS = {".git", ".hg", ".svn", ".venv", "venv", "env", "node_modules", "__pycache__",
                  ".tox", ".eggs", "site-packages", ".mypy_cache", ".pytest_cache"}

#: Code that someone else owns or a tool wrote; the next update would undo a change.
VENDORED_DIRS = {"vendor", "vendored", "third_party", "thirdparty", "external", "extern",
                 "generated", "gen", "build", "dist"}
_GENERATED_MARKERS = ("do not edit", "generated by", "auto-generated", "autogenerated", "@generated")


class SeatBrokeCharter(RuntimeError):
    """A seat-filler changed the tree when its role does not allow it."""


def _walk(target: Path) -> Iterator[Path]:
    for path in sorted(Path(target).rglob("*")):
        if path.is_file() and not _SKIP.intersection(path.relative_to(target).parts):
            yield path


def _env_stats(target: Path) -> Dict[str, tuple]:
    """Name, size and time of every file under an environment folder (see `_ENV_DIRS`)."""
    out: Dict[str, tuple] = {}
    for path in Path(target).rglob("*"):
        parts = path.relative_to(target).parts
        if ".git" in parts or not _ENV_DIRS.intersection(parts) or not path.is_file():
            continue
        st = path.stat()
        out[str(path.relative_to(target))] = (st.st_size, st.st_mtime_ns)
    return out


def _git_guard(target: Path) -> Dict[str, bytes]:
    """The parts of .git that can run code or redirect git: hooks, config, info, and stray lock files.

    The rest of .git is skipped by the snapshot (it is large and git rewrites
    it on its own), but these files are read byte for byte.
    """
    git = Path(target) / ".git"
    out: Dict[str, bytes] = {}
    if not git.is_dir():
        return out
    if (git / "config").is_file():
        out[".git/config"] = (git / "config").read_bytes()
    # Lock files git leaves while it works. One a seat creates blocks the user's own git commands.
    for path in sorted(git.glob("*.lock")):
        if path.is_file():
            out[".git/" + path.name] = path.read_bytes()
    for sub in ("hooks", "info"):
        base = git / sub
        if base.is_dir():
            for path in sorted(base.rglob("*")):
                if path.is_file():
                    out[".git/" + path.relative_to(git).as_posix()] = path.read_bytes()
    return out


class Snapshot:
    """Every file under the target as it was, so a surprise can be named and undone."""

    def __init__(self, target: Path) -> None:
        self.target = Path(target)
        self.files: Dict[str, bytes] = {}
        self.restorable = True
        total = 0
        for path in _walk(self.target):
            data = path.read_bytes()
            total += len(data)
            self.restorable = self.restorable and total <= _RESTORE_LIMIT
            self.files[str(path.relative_to(self.target))] = data if self.restorable else b""
        if not self.restorable:
            self.files = {k: b"" for k in self.files}
        self._stat = self._stats()
        self._env = _env_stats(self.target)
        self.dirs = self._dirs()
        self.git = _git_guard(self.target)

    def _dirs(self) -> set:
        return {str(p.relative_to(self.target)) for p in sorted(self.target.rglob("*"))
                if p.is_dir() and not p.is_symlink() and not _SKIP.intersection(p.relative_to(self.target).parts)}

    def _stats(self) -> Dict[str, tuple]:
        return {str(p.relative_to(self.target)): (p.stat().st_size, p.stat().st_mtime_ns)
                for p in _walk(self.target)}

    def changes(self) -> list[str]:
        now = self._stats()
        out = [f"added {k}" for k in now.keys() - self._stat.keys()]
        out += [f"added folder {k}" for k in self._dirs() - self.dirs]
        out += [f"removed {k}" for k in self._stat.keys() - now.keys()]
        for k in now.keys() & self._stat.keys():
            if self.restorable:
                # Bytes, not size and time: a same-size write with the old time put back would pass a stat check.
                if (self.target / k).read_bytes() != self.files[k]:
                    out.append(f"changed {k}")
            elif now[k] != self._stat[k]:
                out.append(f"changed {k}")
        env_now = _env_stats(self.target)
        out += [f"added {k}" for k in env_now.keys() - self._env.keys()]
        out += [f"removed {k}" for k in self._env.keys() - env_now.keys()]
        out += [f"changed {k}" for k in env_now.keys() & self._env.keys() if env_now[k] != self._env[k]]
        git_now = _git_guard(self.target)
        out += [f"added {k}" for k in git_now.keys() - self.git.keys()]
        out += [f"removed {k}" for k in self.git.keys() - git_now.keys()]
        out += [f"changed {k}" for k in git_now.keys() & self.git.keys() if git_now[k] != self.git[k]]
        return sorted(out)

    def _restore_git(self) -> None:
        now = _git_guard(self.target)
        for rel in now.keys() - self.git.keys():
            (self.target / rel).unlink(missing_ok=True)
        for rel, data in self.git.items():
            path = self.target / rel
            if not path.is_file() or path.read_bytes() != data:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)

    def restore(self) -> None:
        self._restore_git()
        # A file added under an environment folder is removed (nothing was there before); a changed
        # one stays, since those folders are watched, not copied, and `changes()` keeps naming it.
        for rel in _env_stats(self.target).keys() - self._env.keys():
            (self.target / rel).unlink(missing_ok=True)
        if not self.restorable:
            return
        now = {str(p.relative_to(self.target)) for p in _walk(self.target)}
        for rel in now - self.files.keys():
            (self.target / rel).unlink(missing_ok=True)
        for rel, data in self.files.items():
            path = self.target / rel
            if not path.is_file() or path.read_bytes() != data:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
        # Folders that did not exist at the start and are now empty (an apply made them) go too.
        for rel in sorted(self._dirs() - self.dirs, key=lambda r: r.count("/"), reverse=True):
            try:
                (self.target / rel).rmdir()
            except OSError:
                pass  # not empty, or already gone


@contextmanager
def watch(target: Path, who: str) -> Iterator[None]:
    """Run a seat that must not write. If it did, undo it and say so."""
    snap = Snapshot(target)
    try:
        yield
    except BaseException:
        snap._restore_git()  # hooks and config are put back even if the seat crashed
        raise
    changed = snap.changes()
    if changed:
        snap.restore()
        left = snap.changes()
        undone = ("and undone" if not left
                  else "and NOT undone (tree too large to restore)" if not snap.restorable
                  else f"and NOT fully undone (still different: {', '.join(left[:3])})")
        raise SeatBrokeCharter(
            f"{who} changed the tree while it had control, which its role does not allow "
            f"({', '.join(changed[:5])}{'...' if len(changed) > 5 else ''}) {undone}.")


def inside(target: Path, rel: str) -> bool:
    candidate = Path(rel)
    if candidate.is_absolute():
        return False
    return (Path(target) / candidate).resolve().is_relative_to(Path(target).resolve())


def _norm(name: str) -> str:
    """A path part as it is compared: NFKC, lower case, no trailing dots or spaces."""
    return unicodedata.normalize("NFKC", name).casefold().rstrip(" .")


def _name_parts(rel: str) -> tuple:
    return tuple(_norm(p) for p in PurePosixPath(rel.replace("\\", "/")).parts)


def _matches(name: str, patterns: Iterable[str]) -> bool:
    return any(fnmatch.fnmatchcase(name, pat) for pat in patterns)


def is_protected(rel: str, extra_dirs: Iterable[str] = ()) -> bool:
    """True for a file that decides acceptability or how the project is built, tested or shipped.

    `extra_dirs` are folders (relative to the target) that are also protected, such as the one
    git's core.hooksPath names.
    """
    parts = _name_parts(rel)
    name = parts[-1] if parts else ""
    dirs = parts[:-1]
    extra = [_name_parts(d) for d in extra_dirs]
    return (name in _PROTECTED_NAMES or _matches(name, _PROTECTED_PATTERNS)
            or bool(_PROTECTED_DIRS.intersection(dirs))
            or any(_matches(d, _PROTECTED_DIR_PATTERNS) for d in dirs)
            or (bool(_NONPROSE_DIRS.intersection(dirs)) and PurePosixPath(name).suffix in {".txt", ".in", ".pip"})
            or any(e and parts[:len(e)] == e for e in extra))


def is_test_code(rel: str) -> bool:
    """Test files and their folders only (the subset of `is_protected` that is Python test code)."""
    parts = _name_parts(rel)
    name = parts[-1] if parts else ""
    return (name in {"conftest.py", "tests.py"} or name.startswith("test_") or name.endswith("_test.py")
            or bool({"tests", "test", "testing"}.intersection(parts[:-1])))


#: Text files that are data or legal text, not prose a documentation grant may rewrite.
_NONPROSE_PATTERNS = ("*requirements*.txt", "*constraints*.txt", "cmakelists.txt", "cmakecache.txt", "license*",
                      "licence*", "notice*", "copying*", "robots.txt", "manifest.txt", "sources.txt",
                      "top_level.txt", "entry_points.txt", "dependency_links.txt", "version.txt", "runtime.txt")
_NONPROSE_DIRS = {"requirements", "constraints", "reqs"}


def is_prose(rel: str) -> bool:
    """True only for real prose: .md, .rst or .txt that is not a requirements list, build file or license."""
    parts = _name_parts(rel)
    name = parts[-1] if parts else ""
    if PurePosixPath(name).suffix not in PROSE:
        return False
    return not (_matches(name, _NONPROSE_PATTERNS) or _NONPROSE_DIRS.intersection(parts[:-1]))


def real_rel(target: Path, rel: str) -> Optional[str]:
    """Where `rel` really lands inside the target once every symlink is followed, or None if outside."""
    root = Path(target).resolve()
    try:
        return (root / rel).resolve().relative_to(root).as_posix()
    except (ValueError, OSError, RuntimeError):
        return None


def hooks_dirs(target: Path) -> tuple:
    """Folders inside the target that git runs hooks from (core.hooksPath), relative to the target."""
    path = gitstate.hooks_path(Path(target))
    if path is None:
        return ()
    root = Path(target).resolve()
    try:
        return (path.resolve().relative_to(root).as_posix(),)
    except ValueError:
        return ()


def format_only(target: Path, edit) -> bool:
    """True when a Python edit changes no behavior: the syntax tree is identical.

    Comments and whitespace are not in the tree, so tidying them passes; any
    changed name, value, statement or docstring does not. This is what lets a
    finisher tidy a test file without being able to weaken it.
    """
    path = Path(target) / edit.path
    if path.suffix != ".py" or not path.is_file() or edit.kind not in {"write", "replace"}:
        return False
    try:
        old = textio.read_text(path)
    except textio.Undecodable:
        return False
    new = edit.new if edit.kind == "write" else old.replace(edit.old, edit.new, 1)
    try:
        return ast.dump(ast.parse(old)) == ast.dump(ast.parse(new))
    except SyntaxError:
        return False


def scope_allows(auth: Authorization, rel: str) -> bool:
    """A documentation grant covers prose only. "code" covers the rest."""
    if auth.scope.strip().lower() in {"code", "all"}:
        return True
    return is_prose(rel)


def _parts(rel: str) -> tuple:
    return tuple(p.lower() for p in PurePosixPath(rel.replace("\\", "/")).parts)


def is_forbidden(target: Path, rel: str) -> bool:
    """True when the path (or where a link in it really points) is inside a VCS, environment or cache directory."""
    if FORBIDDEN_DIRS.intersection(_parts(rel)):
        return True
    try:
        real = (Path(target) / rel).resolve().relative_to(Path(target).resolve())
    except ValueError:
        return False
    return bool(FORBIDDEN_DIRS.intersection(p.lower() for p in real.parts))


def is_vendored(target: Path, rel: str) -> bool:
    """True for vendored or generated code: a vendor-like directory, or a "generated" banner in the first 10 lines."""
    if VENDORED_DIRS.intersection(_parts(rel)[:-1]):
        return True
    path = Path(target) / rel
    if not path.is_file():
        return False
    try:
        with path.open("rb") as handle:
            head = b"".join(handle.readline() for _ in range(10)).decode("utf-8", "replace").lower()
    except OSError:
        return False
    return any(marker in head for marker in _GENERATED_MARKERS)


def violation(target: Path, proposal: Transformation, auth: Authorization) -> Optional[tuple[str, str]]:
    """(kind, why) when an edit may not be made, else None.

    kind is "escape" (outside the target, or inside version control, an
    environment or a cache: hostile or broken, stop everything) or "refused"
    (a judging file, a file that is not UTF-8, vendored or generated code:
    decline this one change) or "scope" (the only thing wrong is that an edit is
    outside the grant's scope: nothing else about the proposal is objectionable).
    """
    for edit in proposal.edits:
        if not inside(target, edit.path):
            return "escape", f"edit path {edit.path!r} is outside the authorized target"
    for edit in proposal.edits:
        if is_forbidden(target, edit.path):
            return "escape", (f"edit path {edit.path!r} is inside version control, an environment or a "
                              "cache, which no change may touch")
    code_scope = auth.scope.strip().lower() in {"code", "all"}
    hooks = hooks_dirs(target)
    out_of_scope: Optional[tuple[str, str]] = None
    for edit in proposal.edits:
        path = Path(target) / edit.path
        # What the edit really touches once symlinks are followed. A link inside the target that points
        # at a protected or non-prose file is that file, whatever the link is called.
        real = real_rel(target, edit.path) or edit.path
        if path.is_file() and not textio.is_decodable(path):
            return "refused", f"{edit.path} is not valid UTF-8, so it will not be edited"
        if (code_scope or not is_prose(edit.path) or not is_prose(real)) and (
                is_vendored(target, edit.path) or is_vendored(target, real)):
            return "refused", (f"{edit.path}: this looks vendored or generated, so a change would be "
                               "undone by the next update")
        if (is_protected(edit.path, hooks) or is_protected(real, hooks)) and not format_only(target, edit):
            return "refused", (f"{edit.path} decides whether a change is acceptable or how the project is built "
                               "and run (tests, test or build configuration, CI, dependency lists, git hooks); "
                               "the loop may not edit it")
        if not (scope_allows(auth, edit.path) and scope_allows(auth, real)) and out_of_scope is None:
            out_of_scope = ("scope", f"{edit.path} is outside the grant's scope {auth.scope!r} "
                                     "(a documentation grant covers prose only)")
    # "scope" means that was the ONLY thing wrong: every other check passed for every edit.
    return out_of_scope
